#!/usr/bin/env node
/**
 * T9 build-time SEO metadata report.
 *
 * Lists, per locale, the pages whose metadata falls outside the target ranges:
 *   - description shorter than 70 or longer than 160 characters
 *   - title longer than 60 characters
 *   - (non-English only) title identical to the English title
 *   - duplicate titles inside one locale
 *
 * Writes SEO_REPORT.md in the repo root. Informational: does not fail the build.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LOCALES = ["en", "ar", "de", "es", "fr", "hi", "id", "nl", "pt", "ru", "tr"];

function flattenMessages(locale) {
  return JSON.parse(readFileSync(join(ROOT, "messages", `${locale}.json`), "utf8"));
}

function blogArticles(locale) {
  const dir = join(ROOT, "src/content/blog", locale);
  let files;
  try { files = readdirSync(dir).filter((f) => f.endsWith(".json")); } catch { return []; }
  return files.map((f) => {
    try { return JSON.parse(readFileSync(join(dir, f), "utf8")); } catch { return null; }
  }).filter(Boolean);
}

