// Cleaner implementation:
function collect(locale) {
  const m = flattenMessages(locale);
  const siteName = "ChooseTools";
  const pages = [];

  if (m.meta) {
    pages.push({ url: locale === "en" ? "/" : `/${locale}/`, title: m.meta.title, description: m.meta.description });
  }

  for (const [slug, v] of Object.entries(m.categories || {})) {
    const path = locale === "en" ? `/${slug}` : `/${locale}/${slug}`;
    pages.push({ url: path, title: `${v.name} — ${siteName}`, description: v.desc });
  }

  for (const [slug, v] of Object.entries(m.tools || {})) {
    const cat = /* find category */ null;
    // category lookup from en tools index
    pages.push({ url: `__TOOL__${slug}`, title: `${v.name} — ${siteName}`, description: v.desc, _slug: slug });
  }

  // Fix tool URLs using en.json tool category map
  const en = flattenMessages("en");
  // We need category per slug; read tools.ts? Parse from src/lib/tools.ts quickly via regex.
  let toolsTs = "";
  try { toolsTs = readFileSync(join(ROOT, "src/lib/tools.ts"), "utf8"); } catch {}
  const catBySlug = {};
  for (const m2 of toolsTs.matchAll(/slug:\s*"([^"]+)"[\s\S]*?category:\s*"([^"]+)"/g)) {
    catBySlug[m2[1]] = m2[2];
  }
  for (const p of pages) {
    if (p.url.startsWith("__TOOL__")) {
      const slug = p._slug;
      const category = catBySlug[slug] || "tools";
      const path = locale === "en" ? `/${category}/${slug}` : `/${locale}/${category}/${slug}`;
      p.url = path;
      delete p._slug;
    }
  }

  // Blog
  for (const a of blogArticles(locale)) {
    const path = locale === "en" ? `/blog/${a.slug}` : `/${locale}/blog/${a.slug}`;
    pages.push({ url: path, title: `${a.title} — ${siteName}`, description: a.description });
  }

  return pages;
}

const enPages = collect("en");
const enTitleByPath = new Map(enPages.map((p) => [p.url.replace(/^\/en(?=\/|$)/, ""), p.title]));
// Map english title by a stable key: for tools/categories/blog use the slug tail.
function englishTitleFor(localePageUrl) {
  // Strip locale prefix
  const stripped = localePageUrl.replace(/^\/(ar|de|es|fr|hi|id|nl|pt|ru|tr)(?=\/|$)/, "");
  const enUrl = stripped === "" ? "/" : stripped;
  const enPage = enPages.find((p) => {
    const eu = p.url.replace(/^\/(ar|de|es|fr|hi|id|nl|pt|ru|tr)(?=\/|$)/, "") || "/";
    return eu === enUrl;
  });
  return enPage ? enPage.title : null;
}

let md = "# SEO metadata report (T9)\n\n";
md += "Generated by `scripts/seo-report.mjs`. Thresholds: description 70–160 characters (target 120–155), title ≤ 60 characters.\n";
md += "English descriptions were enriched in this pass; other locales are reported only and need native drafts.\n\n";

const summary = [];

for (const locale of LOCALES) {
  const pages = collect(locale);
  const descShort = pages.filter((p) => (p.description || "").length < 70);
  const descLong = pages.filter((p) => (p.description || "").length > 160);
  const titleLong = pages.filter((p) => (p.title || "").length > 60);

  const titleDupMap = new Map();
  for (const p of pages) {
    const t = p.title || "";
    titleDupMap.set(t, (titleDupMap.get(t) || 0) + 1);
  }
  const dupTitles = [...titleDupMap.entries()].filter(([, c]) => c > 1).map(([t, c]) => ({ title: t, count: c }));

  let sameAsEnglish = [];
  if (locale !== "en") {
    sameAsEnglish = pages.filter((p) => {
      const et = englishTitleFor(p.url);
      return et && p.title === et;
    });
  }

  summary.push({ locale, total: pages.length, descShort: descShort.length, descLong: descLong.length, titleLong: titleLong.length, dup: dupTitles.length, sameAsEn: sameAsEnglish.length });

  md += `## ${locale} (${pages.length} pages)\n\n`;
  md += `- descriptions < 70 chars: **${descShort.length}**\n`;
  md += `- descriptions > 160 chars: **${descLong.length}**\n`;
  md += `- titles > 60 chars: **${titleLong.length}**\n`;
  md += `- duplicate titles: **${dupTitles.length}**\n`;
  if (locale !== "en") md += `- titles identical to English: **${sameAsEnglish.length}**\n`;
  md += "\n";

  if (descShort.length) {
    md += `### Descriptions shorter than 70 chars (${descShort.length})\n`;
    for (const p of descShort.slice(0, 40)) md += `- \`${p.url}\` (${(p.description || "").length}) ${p.description}\n`;
    if (descShort.length > 40) md += `- …and ${descShort.length - 40} more\n`;
    md += "\n";
  }
  if (descLong.length) {
    md += `### Descriptions longer than 160 chars (${descLong.length})\n`;
    for (const p of descLong) md += `- \`${p.url}\` (${(p.description || "").length})\n`;
    md += "\n";
  }
  if (titleLong.length) {
    md += `### Titles longer than 60 chars (${titleLong.length})\n`;
    for (const p of titleLong) md += `- \`${p.url}\` (${(p.title || "").length}) ${p.title}\n`;
    md += "\n";
  }
  if (dupTitles.length) {
    md += `### Duplicate titles (${dupTitles.length})\n`;
    for (const d of dupTitles) md += `- (${d.count}×) ${d.title}\n`;
    md += "\n";
  }
  if (sameAsEnglish.length) {
    md += `### Titles identical to English (${sameAsEnglish.length})\n`;
    for (const p of sameAsEnglish.slice(0, 40)) md += `- \`${p.url}\`\n`;
    if (sameAsEnglish.length > 40) md += `- …and ${sameAsEnglish.length - 40} more\n`;
    md += "\n";
  }
}

md += "## Summary\n\n";
md += "| Locale | Pages | Desc<70 | Desc>160 | Title>60 | Dup titles | =English |\n";
md += "| --- | --- | --- | --- | --- | --- | --- |\n";
for (const s of summary) {
  md += `| ${s.locale} | ${s.total} | ${s.descShort} | ${s.descLong} | ${s.titleLong} | ${s.dup} | ${s.sameAsEn} |\n`;
}

writeFileSync(join(ROOT, "SEO_REPORT.md"), md, "utf8");
console.log("wrote SEO_REPORT.md");
for (const s of summary) console.log(s.locale, "pages", s.total, "desc<70", s.descShort, "desc>160", s.descLong, "title>60", s.titleLong, "dup", s.dup, "=en", s.sameAsEn);
